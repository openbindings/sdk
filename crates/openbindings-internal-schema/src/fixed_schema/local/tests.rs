#[test]
fn depth_and_payload_growth_do_not_repeat_descendant_extent_at_the_parent() {
    for dialect in EDITIONS {
        for depth in [1, 16, 64] {
            let text = format!(
                "{}true{}",
                r#"{"allOf":["#.repeat(depth),
                "]}".repeat(depth)
            );
            let value = JsonValue::parse(text).unwrap();
            assert_eq!(extent(value.view(), dialect, &unlimited()).unwrap(), 13);
            assert!(dialect_validity(&value, dialect).unwrap());
        }
        for width in [1, 128, 2048] {
            let body = (0..width)
                .map(|i| format!(r#""p{i}":{{"default":"{}"}}"#, "x".repeat(128)))
                .collect::<Vec<_>>()
                .join(",");
            let value = JsonValue::parse(format!(r#"{{"properties":{{{body}}}}}"#)).unwrap();
            let expected = value.text().len() - width * (r#"{"default":""}"#.len() + 128 - 1);
            assert_eq!(
                extent(value.view(), dialect, &unlimited()).unwrap(),
                expected
            );
            assert!(dialect_validity(&value, dialect).unwrap());
        }
    }
}

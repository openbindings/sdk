#[test]
fn reference_operand_audit_and_nonasserting_format_policy_are_fixed() {
    let graph = actual();
    let seven =
        &graph["draft7"]["resources"]["https://openbindings.invalid/foreign-meta/draft-07/schema#"];
    let nineteen = &graph["draft2019"]["resources"]["https://openbindings.invalid/foreign-meta/draft/2019-09/meta/core"];
    let twenty =
        &graph["draft2020"]["resources"]["https://openbindings.invalid/internal-meta/meta/core"];
    for operand in [
        &seven["properties"]["$ref"],
        &nineteen["properties"]["$ref"],
        &nineteen["properties"]["$recursiveRef"],
        &twenty["$defs"]["uriReferenceString"],
    ] {
        assert_eq!(*operand, json!({"type":"string","format":"uri-reference"}));
    }
    for keyword in ["$ref", "$dynamicRef"] {
        assert_eq!(
            twenty["properties"][keyword],
            json!({"$ref":"#/$defs/uriReferenceString"})
        );
    }
    let deprecated = &graph["draft2020"]["resources"]["https://openbindings.invalid/internal-meta/schema"]
        ["properties"]["$recursiveRef"];
    assert_eq!(
        deprecated,
        &json!({
            "$comment":"\"$recursiveRef\" has been replaced by \"$dynamicRef\".",
            "$ref":"meta/core#/$defs/uriReferenceString", "deprecated":true
        })
    );
    // The production options, not a test-only copy, must leave URI formats
    // nonasserting. Otherwise these operands read text and cannot be cut.
    let validator = super::super::options(Default::default())
        .build(&json!({"type":"string", "format":"uri-reference"}))
        .unwrap();
    assert!(super::super::valid(
        &validator,
        JsonValue::parse(r#""%""#).unwrap().view()
    ));
    let mut text_sensitive = actual();
    text_sensitive["draft2020"]["resources"]["https://openbindings.invalid/internal-meta/meta/core"]
        ["$defs"]["uriReferenceString"]["maxLength"] = json!(1);
    assert_ne!(text_sensitive, snapshot());
}

#[test]
fn only_audited_reference_strings_drop_their_payload_extent() {
    for dialect in EDITIONS {
        for keyword in [
            "$ref",
            "$dynamicRef",
            "$recursiveRef",
            "$id",
            "$anchor",
            "pattern",
            "unknown",
        ] {
            let audited = keyword == "$ref"
                || (keyword == "$recursiveRef" && dialect != Dialect::Draft7)
                || (keyword == "$dynamicRef" && dialect == Dialect::Draft202012);
            for text in [
                r#""%""#.to_owned(),
                r#""\ud800""#.to_owned(),
                format!("\"{}\"", "x".repeat(10_000)),
            ] {
                let value = JsonValue::parse(format!(r#"{{"{keyword}":{text}}}"#)).unwrap();
                assert_eq!(
                    extent(value.view(), dialect, &unlimited()).unwrap(),
                    value.text().len() - if audited { text.len() - 1 } else { 0 },
                    "{dialect:?} {keyword}"
                );
                if audited {
                    assert_eq!(
                        dialect_validity(&value, dialect).unwrap(),
                        !(dialect == Dialect::Draft7 && text == r#""\ud800""#)
                    );
                }
            }
            for wrong_kind in [
                "null".to_owned(),
                "true".to_owned(),
                "123".to_owned(),
                format!(r#"["{}"]"#, "x".repeat(1000)),
            ] {
                let value = JsonValue::parse(format!(r#"{{"{keyword}":{wrong_kind}}}"#)).unwrap();
                assert_eq!(
                    extent(value.view(), dialect, &unlimited()).unwrap(),
                    value.text().len()
                );
                if audited {
                    assert!(
                        !dialect_validity(&value, dialect).unwrap(),
                        "{dialect:?} {keyword}"
                    );
                }
            }
        }
    }
}

#[test]
fn graph_guard_rejects_child_inspecting_and_nonrecursive_changes() {
    let expected = snapshot();
    let root = "https://openbindings.invalid/internal-meta/schema";
    let applicator = "https://openbindings.invalid/internal-meta/meta/applicator";
    let validation = "https://openbindings.invalid/internal-meta/meta/validation";
    for (resource, pointer, keyword, constraint) in [
        (
            root,
            "/properties/definitions/additionalProperties",
            "const",
            json!({}),
        ),
        (root, "/properties/definitions", "const", json!({"a":false})),
        (applicator, "/$defs/schemaArray", "uniqueItems", json!(true)),
        (validation, "/$defs/stringArray", "maxItems", json!(2)),
    ] {
        let mut changed = actual();
        changed["draft2020"]["resources"][resource]
            .pointer_mut(pointer)
            .unwrap()
            .as_object_mut()
            .unwrap()
            .insert(keyword.into(), constraint);
        assert_ne!(changed, expected);
    }
    // Exercise actual production localization, not a copy inside the guard.
    let mut original: Value = serde_json::from_str(META_FILES[0]).unwrap();
    original["properties"]["definitions"]["additionalProperties"]["$dynamicRef"] =
        json!("#different");
    localize(&mut original);
    let mut changed = actual();
    changed["draft2020"]["resources"][root] = original;
    assert_ne!(changed, expected);
}

#[test]
fn every_localized_recursive_terminal_is_only_a_kind_check() {
    fn walk(original: &Value, localized: &Value, modern: bool, count: &mut usize) {
        match original {
            Value::Object(fields) => {
                let marker = if modern {
                    fields.get("$dynamicRef").is_some_and(|v| v == "#meta")
                } else {
                    ["$ref", "$recursiveRef"]
                        .iter()
                        .any(|k| fields.get(*k).is_some_and(|v| v == "#"))
                };
                if marker {
                    assert_eq!(fields.len(), 1);
                    assert_eq!(localized, &json!({"type":["object","boolean"]}));
                    *count += 1;
                } else {
                    for (k, v) in fields {
                        if k != "$schema" {
                            walk(v, &localized[k], modern, count);
                        }
                    }
                }
            }
            Value::Array(values) => {
                for (i, v) in values.iter().enumerate() {
                    walk(v, &localized[i], modern, count);
                }
            }
            _ => {}
        }
    }
    let mut count = 0;
    for (texts, modern) in [
        (&DRAFT7_FILES[..], false),
        (&DRAFT2019_FILES[..], false),
        (&META_FILES[..], true),
    ] {
        for text in texts {
            let original: Value = serde_json::from_str(text).unwrap();
            let mut localized = original.clone();
            if modern {
                localize(&mut localized);
            } else {
                localize_foreign(&mut localized);
            }
            walk(&original, &localized, modern, &mut count);
        }
    }
    assert_eq!(count, 51);
}

#[test]
fn each_cut_family_retains_headers_and_only_skips_schema_payloads() {
    let child = json!({"type":17,"opaque":"x".repeat(10_000)}).to_string();
    for dialect in EDITIONS {
        for (keyword, shape) in [
            ("definitions", Children::Map),
            ("properties", Children::Map),
            ("patternProperties", Children::Map),
            ("dependencies", Children::Map),
            ("$defs", Children::Map),
            ("dependentSchemas", Children::Map),
            ("allOf", Children::Array),
            ("anyOf", Children::Array),
            ("oneOf", Children::Array),
            ("prefixItems", Children::Array),
            ("additionalItems", Children::Direct),
            ("additionalProperties", Children::Direct),
            ("propertyNames", Children::Direct),
            ("items", Children::Direct),
            ("contains", Children::Direct),
            ("not", Children::Direct),
            ("if", Children::Direct),
            ("then", Children::Direct),
            ("else", Children::Direct),
            ("unevaluatedProperties", Children::Direct),
            ("unevaluatedItems", Children::Direct),
            ("contentSchema", Children::Direct),
        ] {
            let active = match keyword {
                "$defs"
                | "dependentSchemas"
                | "unevaluatedProperties"
                | "unevaluatedItems"
                | "contentSchema" => dialect != Dialect::Draft7,
                "additionalItems" => dialect != Dialect::Draft202012,
                "prefixItems" => dialect == Dialect::Draft202012,
                _ => true,
            };
            let operand = match shape {
                Children::Map => format!(r#"{{"name":{child}}}"#),
                Children::Array => format!("[{child}]"),
                Children::Direct => child.clone(),
            };
            let value = JsonValue::parse(format!(r#"{{"{keyword}":{operand}}}"#)).unwrap();
            let measured = extent(value.view(), dialect, &unlimited()).unwrap();
            assert_eq!(
                measured,
                value.text().len() - if active { child.len() - 1 } else { 0 },
                "{dialect:?} {keyword}"
            );
            // Child's invalid type is not inspected by this LOCAL check.
            assert!(
                dialect_validity(&value, dialect).unwrap(),
                "{dialect:?} {keyword}"
            );
        }
        let tuple = JsonValue::parse(format!(r#"{{"items":[{child}]}}"#)).unwrap();
        let measured = extent(tuple.view(), dialect, &unlimited()).unwrap();
        assert_eq!(
            measured,
            tuple.text().len()
                - if dialect == Dialect::Draft202012 {
                    0
                } else {
                    child.len() - 1
                }
        );
        assert_eq!(
            dialect_validity(&tuple, dialect).unwrap(),
            dialect != Dialect::Draft202012
        );
    }
}

#[test]
fn arrays_opaque_data_wrong_kinds_and_exact_spelling_remain_charged() {
    for dialect in EDITIONS {
        for text in [
            "true",
            "false",
            "null",
            "17",
            r#""text""#,
            r#"{"dependencies":{"a":["same","same"]}}"#,
            r#"{"properties":[{"nested":true}]}"#,
            r#"{"allOf":{"nested":true}}"#,
            r#"{"not":17}"#,
            r#"{"default":{"not":{"deep":true}},"unknown":{"properties":{"x":true}}}"#,
            r#"{"const":{"not":true},"enum":[{"not":true}],"examples":[{"not":true}]}"#,
            r#"{"minItems":1e999999999999999999999999999999999999}"#,
            r#"{"required":["\ud800"],"type":["string","string"]}"#,
        ] {
            let value = JsonValue::parse(text).unwrap();
            assert_eq!(
                extent(value.view(), dialect, &unlimited()).unwrap(),
                text.len(),
                "{text}"
            );
        }
        let text = r#"{"propert\u0069es":{"\ud800":{"deep":{"payload":false}}}}"#;
        let value = JsonValue::parse(text).unwrap();
        let child = value
            .get("properties")
            .unwrap()
            .members()
            .unwrap()
            .next()
            .unwrap()
            .value;
        assert_eq!(
            extent(value.view(), dialect, &unlimited()).unwrap(),
            text.len() - child.text().len() + 1
        );
        assert!(dialect_validity(&value, dialect).unwrap());
        // Numeric overrides retain exact values, fixed formats remain annotations.
        for (text, valid) in [
            (r#"{"minItems":-1e-999999999999999999999999}"#, false),
            (r#"{"$id":"not a uri","pattern":"["}"#, true),
            (r#"{"dependencies":{"x":["a","a"]}}"#, false),
        ] {
            assert_eq!(
                dialect_validity(&JsonValue::parse(text).unwrap(), dialect).unwrap(),
                valid
            );
        }
    }
}

fn bounded(
    value: &JsonValue,
    dialect: Dialect,
    work: usize,
    allocation: usize,
    control: &dyn Control,
) -> Result<bool, Failure> {
    Attempt::run(work, allocation, control, |a| {
        dialect_validity_bounded(value, dialect, a)
    })
    .and_then(|r| r)
}

#[test]
fn exact_limits_cancellation_and_nested_attempts_remain_authoritative() {
    let value = JsonValue::parse(
        r#"{"properties":{"a":{"type":"string"},"b":true},"dependencies":{"x":["a","b"]}}"#,
    )
    .unwrap();
    for dialect in EDITIONS {
        assert!(dialect_validity(&value, dialect).unwrap()); // Warm this fixed compiler.
        let bytes = extent(value.view(), dialect, &unlimited()).unwrap();
        let allocation = 64 * bytes + 4096;
        assert!(bounded(&value, dialect, usize::MAX, allocation, &unlimited()).unwrap());
        assert_eq!(
            bounded(&value, dialect, usize::MAX, allocation - 1, &unlimited())
                .unwrap_err()
                .reason,
            FailureReason::LimitExceeded
        );
        let (mut lo, mut hi) = (0, 1_000_000);
        while lo < hi {
            let mid = lo + (hi - lo) / 2;
            if bounded(&value, dialect, mid, allocation, &unlimited()).is_ok() {
                hi = mid;
            } else {
                lo = mid + 1;
            }
        }
        assert!(bounded(&value, dialect, lo, allocation, &unlimited()).unwrap());
        assert_eq!(
            bounded(&value, dialect, lo - 1, allocation, &unlimited())
                .unwrap_err()
                .reason,
            FailureReason::LimitExceeded
        );
        let control = unlimited();
        assert!(bounded(&value, dialect, usize::MAX, allocation, &control).unwrap());
        for boundary in 0..control.checks.load(Ordering::Relaxed) {
            assert_eq!(
                bounded(
                    &value,
                    dialect,
                    usize::MAX,
                    allocation,
                    &ControlProbe::new(boundary)
                )
                .unwrap_err()
                .reason,
                FailureReason::Cancelled
            );
        }
        assert!(bounded(&value, dialect, usize::MAX, allocation, &unlimited()).unwrap());
        let failed = Attempt::run(usize::MAX, allocation - 1, &unlimited(), |outer| {
            let _ = Attempt::run(usize::MAX, usize::MAX, outer, |inner| {
                dialect_validity_bounded(&value, dialect, inner)
            });
            true // An ignored failure cannot manufacture Ready.
        });
        assert_eq!(failed.unwrap_err().reason, FailureReason::LimitExceeded);
        let failed = Attempt::run(lo - 1, usize::MAX, &unlimited(), |outer| {
            let _ = dialect_validity_bounded(&value, dialect, outer);
            true
        });
        assert_eq!(failed.unwrap_err().reason, FailureReason::LimitExceeded);
    }
}


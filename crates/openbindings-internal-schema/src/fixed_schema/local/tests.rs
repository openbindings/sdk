use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

struct ControlProbe {
    checks: AtomicUsize,
    cancel_at: usize,
    exhausted: AtomicBool,
}
impl ControlProbe {
    fn new(cancel_at: usize) -> Self {
        Self {
            checks: AtomicUsize::new(0),
            cancel_at,
            exhausted: AtomicBool::new(false),
        }
    }
}
impl Control for ControlProbe {
    fn is_cancelled(&self) -> bool {
        self.checks.fetch_add(1, Ordering::Relaxed) >= self.cancel_at
    }
    fn allocation_limit_reached(&self) {
        self.exhausted.store(true, Ordering::Relaxed);
    }
    fn allocation_is_exhausted(&self) -> bool {
        self.exhausted.load(Ordering::Relaxed)
    }
}
fn unlimited() -> ControlProbe {
    ControlProbe::new(usize::MAX)
}
const EDITIONS: [Dialect; 3] = [Dialect::Draft7, Dialect::Draft201909, Dialect::Draft202012];

fn snapshot() -> Value {
    serde_json::from_str(include_str!("resources.json")).unwrap()
}
fn selected(root: Value, resources: std::collections::BTreeMap<String, Value>) -> Value {
    let entry = root["$id"].as_str().unwrap();
    assert_eq!(resources.get(entry), Some(&root));
    json!({"entry": entry, "resources": resources})
}
fn actual() -> Value {
    let (seven_root, seven) = foreign_meta_resources(&DRAFT7_FILES).unwrap();
    let (nineteen_root, nineteen) = foreign_meta_resources(&DRAFT2019_FILES).unwrap();
    let twenty = meta_resources().unwrap();
    let twenty_root = meta_root(&twenty).unwrap().clone();
    assert_eq!((seven.len(), nineteen.len(), twenty.len()), (1, 7, 8));
    json!({"draft7": selected(seven_root,seven), "draft2019": selected(nineteen_root,nineteen), "draft2020": selected(twenty_root,twenty)})
}

#[test]
fn graph_guard_covers_the_compilers_selected_entry() {
    let mut reordered = DRAFT2019_FILES;
    reordered.swap(0, 1);
    let (root, resources) = foreign_meta_resources(&reordered).unwrap();
    let changed = selected(root, resources);
    // Resource maps alone cannot detect the compiler starting at meta/core.
    assert_eq!(changed["resources"], snapshot()["draft2019"]["resources"]);
    assert_ne!(changed, snapshot()["draft2019"]);
    let mut altered_root = serde_json::from_str::<Value>(DRAFT7_FILES[0]).unwrap();
    altered_root["type"] = json!("array");
    let altered_text = altered_root.to_string();
    let (root, resources) = foreign_meta_resources(&[&altered_text]).unwrap();
    assert_ne!(selected(root, resources), snapshot()["draft7"]);
}

